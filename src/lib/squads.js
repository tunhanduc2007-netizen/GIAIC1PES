// Chuẩn hóa tên đội bóng để tra cứu dễ dàng
const normalizeClubName = (name = '') => {
  return name.toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, '');
};

// Lấy danh sách cầu thủ chuyển nhượng tùy chỉnh do người dùng thêm vào
export const getCustomTransfers = () => {
  try {
    const raw = localStorage.getItem('pes_c1_custom_transfers_v1');
    return raw ? JSON.parse(raw) : {};
  } catch (e) {
    return {};
  }
};

// Thêm cầu thủ chuyển nhượng mới vào CLB
export const addTransferPlayer = (clubName, playerName, pos = 'FW') => {
  if (!clubName || !playerName || !playerName.trim()) return;
  const current = getCustomTransfers();
  const list = current[clubName] || [];
  const cleanName = playerName.trim();
  if (!list.some(p => p.name.toLowerCase() === cleanName.toLowerCase())) {
    current[clubName] = [{ name: cleanName, pos: pos.toUpperCase(), isCustom: true }, ...list];
    try {
      localStorage.setItem('pes_c1_custom_transfers_v1', JSON.stringify(current));
    } catch (e) {
      console.error(e);
    }
  }
};

// Xóa cầu thủ chuyển nhượng đã thêm
export const removeTransferPlayer = (clubName, playerName) => {
  if (!clubName || !playerName) return;
  const current = getCustomTransfers();
  if (current[clubName]) {
    current[clubName] = current[clubName].filter(p => p.name.toLowerCase() !== playerName.toLowerCase());
    try {
      localStorage.setItem('pes_c1_custom_transfers_v1', JSON.stringify(current));
    } catch (e) {
      console.error(e);
    }
  }
};

// Tìm đội hình theo tên CLB (linh hoạt theo từ khóa & kết hợp chuyển nhượng mới)
export const getClubSquad = (clubName) => {
  if (!clubName) return [];

  let baseSquad = [];
  if (CLUB_SQUADS[clubName]) {
    baseSquad = CLUB_SQUADS[clubName];
  } else {
    const target = normalizeClubName(clubName);
    for (const [name, squad] of Object.entries(CLUB_SQUADS)) {
      const norm = normalizeClubName(name);
      if (norm === target || norm.includes(target) || target.includes(norm)) {
        baseSquad = squad;
        break;
      }
    }

    if (baseSquad.length === 0) {
      // Một số alias thông dụng
      if (target.includes('barca')) baseSquad = CLUB_SQUADS['Barcelona'] || [];
      else if (target.includes('real')) baseSquad = CLUB_SQUADS['Real Madrid'] || [];
      else if (target.includes('atletico') || target.includes('atm')) baseSquad = CLUB_SQUADS['Atlético Madrid'] || [];
      else if (target.includes('manchesterunited') || target.includes('manutd') || target.includes('mu')) baseSquad = CLUB_SQUADS['Manchester United'] || [];
      else if (target.includes('manchestercity') || target.includes('mancity') || target.includes('mc')) baseSquad = CLUB_SQUADS['Manchester City'] || [];
      else if (target.includes('inter')) baseSquad = CLUB_SQUADS['Inter Milan'] || [];
      else if (target.includes('dortmund') || target.includes('bvb')) baseSquad = CLUB_SQUADS['Borussia Dortmund'] || [];
      else if (target.includes('bayern')) baseSquad = CLUB_SQUADS['Bayern Munich'] || [];
      else if (target.includes('bilbao')) baseSquad = CLUB_SQUADS['Athletic Bilbao'] || [];
      else if (target.includes('sporting')) baseSquad = CLUB_SQUADS['Sporting CP'] || [];
      else if (target.includes('betis')) baseSquad = CLUB_SQUADS['Real Betis'] || [];
      else if (target.includes('leipzig')) baseSquad = CLUB_SQUADS['RB Leipzig'] || [];
    }
  }

  // Kết hợp thêm các cầu thủ chuyển nhượng tùy chỉnh của người dùng
  const custom = getCustomTransfers();
  const added = custom[clubName] || [];

  if (added.length === 0) return baseSquad;

  const existingNames = new Set(baseSquad.map(p => p.name.toLowerCase()));
  const filteredAdded = added.filter(p => !existingNames.has(p.name.toLowerCase()));

  // Đưa các bản hợp đồng mới lên đầu danh sách để dễ chọn nhất
  return [...filteredAdded, ...baseSquad];
};

